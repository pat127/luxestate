// Flat list of all areas for simple dropdowns
export const ALL_UAE_AREAS: string[] = UAE_LOCATIONS.map((l) => l.area);

// Flat list of all communities
export const ALL_UAE_COMMUNITIES: string[] = UAE_LOCATIONS.flatMap((l) => l.communities);

// Get communities for a given area
export function getCommunitiesForArea(area: string): string[] {
  const found = UAE_LOCATIONS.find((l) => l.area === area);
  return found ? found.communities : [];
}

// Get all areas for a given emirate
export function getAreasForEmirate(emirate: string): string[] {
  return UAE_LOCATIONS.filter((l) => l.emirate === emirate).map((l) => l.area);
}

